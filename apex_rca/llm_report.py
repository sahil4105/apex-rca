"""Structured diagnosis report models for LLM-based root-cause analysis."""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from typing import Any, Literal


ConfidenceLevel = Literal["high", "medium", "low"]


@dataclass
class SupportingClaim:
    """A specific factual claim linked to one or more evidence IDs."""

    claim_text: str
    evidence_ids: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {"claim_text": self.claim_text, "evidence_ids": list(self.evidence_ids)}


@dataclass
class AlternativeCandidate:
    """A secondary suspect service considered during diagnosis."""

    service: str
    rationale: str

    def to_dict(self) -> dict[str, Any]:
        return {"service": self.service, "rationale": self.rationale}


@dataclass
class IncidentReport:
    """Validated structured diagnosis report generated by or for the LLM."""

    suspected_root_cause: str
    confidence: ConfidenceLevel
    possible_fault_type: str | None
    reasoning_summary: str
    supporting_claims: list[SupportingClaim] = field(default_factory=list)
    alternative_candidates: list[AlternativeCandidate] = field(default_factory=list)
    contradictory_evidence: list[str] = field(default_factory=list)
    uncertainty_and_limitations: list[str] = field(default_factory=list)
    raw_response: str | None = None
    model_name: str | None = None
    generation_latency_s: float = 0.0
    prompt_tokens: int | None = None
    completion_tokens: int | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "suspected_root_cause": self.suspected_root_cause,
            "confidence": self.confidence,
            "possible_fault_type": self.possible_fault_type,
            "reasoning_summary": self.reasoning_summary,
            "supporting_claims": [claim.to_dict() for claim in self.supporting_claims],
            "alternative_candidates": [cand.to_dict() for cand in self.alternative_candidates],
            "contradictory_evidence": list(self.contradictory_evidence),
            "uncertainty_and_limitations": list(self.uncertainty_and_limitations),
            "model_name": self.model_name,
            "generation_latency_s": self.generation_latency_s,
            "prompt_tokens": self.prompt_tokens,
            "completion_tokens": self.completion_tokens,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_dict(cls, data: dict[str, Any], raw_response: str | None = None) -> IncidentReport:
        claims = [
            SupportingClaim(
                claim_text=str(c.get("claim_text", "")),
                evidence_ids=[str(eid) for eid in c.get("evidence_ids", [])],
            )
            for c in data.get("supporting_claims", [])
            if isinstance(c, dict)
        ]
        alternatives = [
            AlternativeCandidate(
                service=str(a.get("service", "")),
                rationale=str(a.get("rationale", "")),
            )
            for a in data.get("alternative_candidates", [])
            if isinstance(a, dict)
        ]
        contradictions = [str(x) for x in data.get("contradictory_evidence", [])]
        limitations = [str(x) for x in data.get("uncertainty_and_limitations", [])]

        conf = str(data.get("confidence", "low")).lower()
        if conf not in {"high", "medium", "low"}:
            conf = "low"

        return cls(
            suspected_root_cause=str(data.get("suspected_root_cause", "")).strip(),
            confidence=conf,  # type: ignore[arg-type]
            possible_fault_type=(
                str(data["possible_fault_type"]).strip()
                if data.get("possible_fault_type")
                else None
            ),
            reasoning_summary=str(data.get("reasoning_summary", "")).strip(),
            supporting_claims=claims,
            alternative_candidates=alternatives,
            contradictory_evidence=contradictions,
            uncertainty_and_limitations=limitations,
            raw_response=raw_response,
            model_name=data.get("model_name"),
            generation_latency_s=float(data.get("generation_latency_s", 0.0)),
            prompt_tokens=data.get("prompt_tokens"),
            completion_tokens=data.get("completion_tokens"),
        )

    @classmethod
    def fallback_from_deterministic(
        cls,
        ranked_candidates: list[tuple[str, float]],
        explanations: list[dict[str, Any]],
        note: str = "Deterministic fallback: LLM generation was not executed or failed.",
    ) -> IncidentReport:
        """Create a deterministic baseline report when LLM is unavailable or fails."""
        top_service = ranked_candidates[0][0] if ranked_candidates else "unknown"
        claims: list[SupportingClaim] = []
        for exp in explanations[:3]:
            svc = exp.get("service", "")
            reasons = exp.get("reasons", [])
            if reasons:
                claims.append(
                    SupportingClaim(
                        claim_text=f"{svc}: {'; '.join(reasons[:2])}",
                        evidence_ids=[],
                    )
                )

        alternatives = [
            AlternativeCandidate(
                service=svc,
                rationale=f"Ranked #{i+1} with combined score {score:.3f}.",
            )
            for i, (svc, score) in enumerate(ranked_candidates[1:3])
        ]

        return cls(
            suspected_root_cause=top_service,
            confidence="medium" if ranked_candidates else "low",
            possible_fault_type=None,
            reasoning_summary=(
                f"Selected {top_service} based on upstream heuristic ranking "
                f"(top combined anomaly and topology score)."
            ),
            supporting_claims=claims,
            alternative_candidates=alternatives,
            contradictory_evidence=[],
            uncertainty_and_limitations=[
                note,
                "No neural LLM reasoning performed; explanation derived solely from heuristic scoring.",
            ],
            model_name="deterministic_fallback",
        )


def report_json_schema() -> dict[str, Any]:
    """JSON schema for prompting and response validation."""
    return {
        "type": "object",
        "properties": {
            "suspected_root_cause": {
                "type": "string",
                "description": "The microservice identified as the primary root cause.",
            },
            "confidence": {
                "type": "string",
                "enum": ["high", "medium", "low"],
                "description": "Confidence level in this root-cause diagnosis.",
            },
            "possible_fault_type": {
                "type": ["string", "null"],
                "description": "Suspected fault type (e.g., cpu_exhaustion, memory_leak, network_latency, pod_failure) or null if uncertain.",
            },
            "reasoning_summary": {
                "type": "string",
                "description": "Concise summary of the diagnosis explaining why this service was chosen over others.",
            },
            "supporting_claims": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "claim_text": {"type": "string"},
                        "evidence_ids": {
                            "type": "array",
                            "items": {"type": "string"},
                            "description": "Exact evidence IDs from the prompt supporting this claim (e.g. ['EVID-METRIC-01']).",
                        },
                    },
                    "required": ["claim_text", "evidence_ids"],
                },
            },
            "alternative_candidates": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "service": {"type": "string"},
                        "rationale": {"type": "string"},
                    },
                    "required": ["service", "rationale"],
                },
            },
            "contradictory_evidence": {
                "type": "array",
                "items": {"type": "string"},
                "description": "Evidence IDs or observations that seem inconsistent or do not support this root cause.",
            },
            "uncertainty_and_limitations": {
                "type": "array",
                "items": {"type": "string"},
                "description": "Acknowledged data gaps, missing modalities, or ambiguities.",
            },
        },
        "required": [
            "suspected_root_cause",
            "confidence",
            "possible_fault_type",
            "reasoning_summary",
            "supporting_claims",
            "alternative_candidates",
            "contradictory_evidence",
            "uncertainty_and_limitations",
        ],
    }

